// Embed the built-in skill files under skills/ as bytes. This reads files and
// serializes them; it does not parse them. Frontmatter is parsed at runtime by
// the shared parseSkill, the same as for any other skill.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const skills = new URL("../skills/", import.meta.url);
const output = new URL("../src/platform-skills.generated.ts", import.meta.url);

async function filesUnder(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = new URL(
      entry.name + (entry.isDirectory() ? "/" : ""),
      directory,
    );
    if (entry.isDirectory()) found.push(...(await filesUnder(path)));
    else found.push(path);
  }
  return found;
}

/** The generated module's text for the files now under skills/. */
export async function renderPlatformSkills() {
  const root = fileURLToPath(skills);
  const files = [];
  for (const file of await filesUnder(skills)) {
    files.push({
      path: relative(root, fileURLToPath(file)).split("\\").join("/"),
      content: await readFile(file, "utf8"),
    });
  }
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const source = [
    "// Generated by scripts/platform-skills.mjs from skills/. Do not edit.",
    "/** Built-in skill files, paths relative to skills/. */",
    `export const platformSkillFiles = ${JSON.stringify(files)} as const;`,
    "",
  ].join("\n");
  const file = fileURLToPath(output);
  return format(source, { ...(await resolveConfig(file)), filepath: file });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await writeFile(output, await renderPlatformSkills());
