test("Prints references use the captured Computer through native MEDIA and saved output replays without generation", async (t) => {
  const png = Buffer.from(
    "iVBORw0KGgoAAAANSUhEUgAAAEAAAAAwCAYAAAChS3wfAAAACXBIWXMAAAPoAAAD6AG1e1JrAAAAlklEQVRogeXOMQEAIAzAsMqZJgSgBtGTkYMjf5rz7s/SAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gEtHdDSAS0d0NIBLR3Q0gFtAcdLcQBrp4b3AAAAAElFTkSuQmCC",
    "base64",
  );
  const { bucket, operations } = mediaStorage(t);
  const files = r2FileSource(bucket, "computer-media/");
  await files.mkdir("/canon");
  await files.write("/canon/style.png", png);
  let dispatches = 0;
  const env = {
    MEDIA_OPERATION: operations,
    IMAGES: {
      info: async (stream) => {
        assert.deepEqual(
          new Uint8Array(await new globalThis.Response(stream).arrayBuffer()),
          Uint8Array.from(png),
        );
        return { format: "image/png", width: 64, height: 48 };
      },
      input: () => assert.fail("a bounded reference needs no resize"),
    },
    AI: {
      run: async (_model, input) => {
        dispatches += 1;
        const form = await new globalThis.Response(input.multipart.body, {
          headers: { "Content-Type": input.multipart.contentType },
        }).formData();
        assert.equal(form.getAll("input_image_0").length, 1);
        const image = z
          .instanceof(globalThis.Blob)
          .parse(form.get("input_image_0"));
        assert.deepEqual(
          new Uint8Array(await image.arrayBuffer()),
          Uint8Array.from(png),
        );
        return { image: png.toString("base64") };
      },
    },
  };
  const instanceId = instanceIds.instance.generate();
  const caller = {
    computerId: "computer-media",
    actor: { kind: "member", memberId: "artist" },
  };
  const facts = invocationFacts.fromCaller(
    {
      instanceId,
      selection: {
        instanceId,
        owner: { kind: "installation", id: "prints" },
        appId: "app_prints",
        releaseId: "rel_fixture",
        authorityVersion: 1,
      },
      artifactDigest: `sha256:${"1".repeat(64)}`,
      grants: [{ binding: "MEDIA", operations: ["models", "generate"] }],
      ancestry: [],
    },
    caller,
    { deadlineAt: Date.now() + 60000, grantExpiresAt: Date.now() + 60000 },
  );
  const gate = createInvocationGate({
    abortGuest: () => Promise.resolve(),
    close: () => Promise.resolve(),
  });
  const owner = createNativeSqliteOwnerFixture();
  t.after(() => owner.close());
  await gate.run(facts, {}, async (frame) => {
    const media = new OysterBinding(
      {
        props: {
          instanceId,
          binding: "MEDIA",
          frameId: frame.frameId,
        },
      },
      {
        ...env,
        INSTANCES: {
          getByName: () => ({
            bindingCall: (props, method, args) =>
              captureFrameBindingReply(() =>
                dispatchMediaBinding(env, frame, props, method, args, {
                  computerId: "computer-media",
                  files,
                }),
              ),
          }),
        },
      },
    );
    const context = new Prints(
      { storage: owner.owner },
      createFrameBindingWire(appInstanceErrorCodeSchema.literals).wrap({
        MEDIA: media,
      }),
    );
    const input = {
      requestId: "media_request_111111111111111111111",
      settings: {
        model: "@cf/black-forest-labs/flux-2-klein-4b",
        prompt: "A mushroom in this style",
        width: 1024,
        height: 1024,
        references: [{ path: "/canon/style.png" }],
      },
    };
    const output = await printsBackend.call(
      "generateImage",
      input,
      context,
      caller,
    );
    assert.equal(output.format, "png", JSON.stringify(output));
    assert.equal(output.destination.computerId, "computer-media");
    assert.ok(output.destination.path.startsWith("/workspace/prints/"));
    const saved = await files.read(output.destination.path);
    assert.equal(saved.length, output.bytes);
    assert.deepEqual(saved.slice(0, 8), Uint8Array.from(png.slice(0, 8)));
    assert.deepEqual(
      await printsBackend.call("generateImage", input, context, caller),
      output,
    );
    assert.equal(dispatches, 1);
    const refused = await printsBackend.call(
      "generateImage",
      {
        ...input,
        requestId: "media_request_222222222222222222222",
        settings: {
          ...input.settings,
          model: "@cf/black-forest-labs/flux-1-schnell",
        },
      },
      context,
      caller,
    );
    assert.equal(refused.error, "INVALID_ARGUMENT");
    assert.equal(refused.stage, "settings");
    assert.equal(dispatches, 1);
  });
});
